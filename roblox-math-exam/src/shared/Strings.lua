local tables: { [string]: { [string]: string } } = { en = en, es = es, pt = pt }

local current = Strings.Default

--- "es-ar" -> "es". Cualquier idioma sin traducir cae en ingles.
function Strings.normalize(localeId: string?): string
	if not localeId then
		return Strings.Default
	end
	local base = string.lower(string.sub(localeId, 1, 2))
	return tables[base] and base or Strings.Default
end

function Strings.setLocale(localeId: string?)
	current = Strings.normalize(localeId)
end

function Strings.getLocale(): string
	return current
end

local function substitute(template: string, args: { [string]: any }?): string
	if not args then
		return template
	end
	return (string.gsub(template, "{(%w+)}", function(name)
		local value = args[name]
		return value ~= nil and tostring(value) or ("{" .. name .. "}")
	end))
end

--- Texto de una clave en el idioma elegido, con sus datos reemplazados.
function Strings.get(key: string, args: { [string]: any }?): string
	local template = tables[current][key] or en[key]
	if not template then
		return key
	end
	return substitute(template, args)
end

--- Igual, pero forzando un idioma (lo usa el selector de Ajustes).
function Strings.forLocale(localeId: string, key: string, args: { [string]: any }?): string
	local locale = Strings.normalize(localeId)
	local template = tables[locale][key] or en[key] or key
	return substitute(template, args)
end

--- Las opciones de relleno viajan como "@clave" para poder traducirse.
function Strings.choice(text: string): string
	if string.sub(text, 1, 1) == "@" then
		return Strings.get(string.sub(text, 2))
	end
	return text
end

return Strings
